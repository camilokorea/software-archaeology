"""The two Markdown reports. Every business statement links to the technical finding behind it; every finding
links to its evidence in the code."""

from __future__ import annotations

from collections import Counter

from archaeology.report.links import cite

SEV_ICON = {"critical": "🔴 critical", "high": "🟠 high", "medium": "🟡 medium", "low": "🔵 low", "info": "⚪ info"}
STATUS = {"red": "🔴 Red", "amber": "🟠 Amber", "green": "🟢 Green"}
KIND = {"verified": "✅ verified by tools", "inferred": "🤖 inferred by AI, checked against the code"}
AREA_TITLE = {"inventory": "Inventory", "dependencies": "Dependencies", "architecture": "Architecture", "database": "Database",
              "api": "API and entry points", "security": "Security", "testing": "Testing", "tech-debt": "Technical debt",
              "devops": "Build, deploy and operations", "risk": "Risk", "capabilities": "Business capabilities", "people": "People and knowledge"}


def _route(a: dict) -> str:
    return f"`{a['path']}`" if a["path"] else "(named by its controller)"


def _anchor(fid: str) -> str:
    return fid.lower()


def _refs(ids: list[str]) -> str:
    return " ".join(f"[{i}](technical.md#{_anchor(i)})" for i in ids)


def technical(ctx: dict) -> str:
    ev, findings, base, diagram = ctx["evidence"], ctx["findings"], ctx["link_base"], ctx["diagram"]
    inv, hist = ev.get("inventory", {}), ev.get("history", {})
    out = [f"# Technical report: {ctx['name']}", "",
           f"Generated by Software Archaeology {ctx['version']} on {ctx['date']} · commit `{(hist.get('head') or 'n/a')[:10]}` · "
           f"analysis: {ctx['provider_label']}", "",
           "Every finding cites the code it is based on. ✅ marks facts produced by tools; 🤖 marks AI inferences that passed the "
           "citation check but deserve a second look.", "", "## Summary", ""]
    sev = Counter(f["severity"] for f in findings)
    out += ["| Severity | Findings |", "|---|---|"] + [f"| {SEV_ICON[s]} | {sev[s]} |" for s in SEV_ICON if sev[s]] + [""]
    out += ["## Inventory", "",
            f"- **Size:** {inv.get('code_lines', 0):,} lines of code in {inv.get('files', 0):,} files ({inv.get('size_class', 'n/a')}).",
            f"- **History:** {hist.get('commits', 'n/a')} commits by {hist.get('contributors', 'n/a')} contributors, "
            f"{hist.get('first_commit', 'n/a')} → {hist.get('last_commit', 'n/a')}; bus factor {hist.get('bus_factor', 'n/a')}."
            if hist.get("available") else "- **History:** no git history available.",
            "- ⚠️ **This is a shallow clone:** history, dates, hotspots and knowledge concentration only cover the commits it contains. "
            "Clone with full history for a complete picture." if hist.get("shallow") else "", "",
            "| Language | Files | Lines of code |", "|---|---:|---:|"]
    out += [f"| {l['language']} | {l['files']:,} | {l['code_lines']:,} |" for l in inv.get("languages", [])[:12] if l["language"] != "Other"]
    out += ["", "**Frameworks and platforms**", ""]
    out += [f"- {f['name']}{' ' + f['detail'] if f.get('detail') else ''} — {cite(f, base)}" for f in inv.get("frameworks", [])] or ["- None recognized."]
    out += ["", "## Architecture (containers)", "", "```mermaid", diagram, "```", "",
            "| Component | Kind | Languages | Manifests |", "|---|---|---|---|"]
    out += [f"| `{c['path']}` | {c['kind']} | {', '.join(c['languages'])} | {', '.join(f'`{m}`' for m in c['manifests'][:3])} |" for c in inv.get("components", [])]
    deps = ev.get("dependencies", {})
    eol = ev.get("eol", [])
    out += ["", "## Dependencies and end of life", "",
            f"{len(deps.get('dependencies', []))} declared dependencies, {len(deps.get('runtimes', []))} runtime declarations.", ""]
    if eol:
        out += ["| Technology | Version | Cycle | End of life | Status | Declared in |", "|---|---|---|---|---|---|"]
        out += [f"| {e.get('label') or e['name']} | {e['version']} | {e['cycle']} | {e['eol']} | {'⛔ past EOL' if e['is_eol'] else 'supported'} | {cite(e, base)} |" for e in eol]
    hot = ev.get("hotspots", [])
    if hot:
        out += ["", "## Hotspots (complexity × change frequency)", "", "| File | Branches | Commits | Authors | Last change | Score |", "|---|---:|---:|---:|---|---:|"]
        out += [f"| {cite({'file': h['path'], 'line': 0}, base)} | {h['decisions']} | {h['commits']} | {h['authors']} | {h['last_change']} | {h['score']} |" for h in hot[:12]]
    api = ev.get("api", [])
    if api:
        fw = Counter(a["framework"] for a in api)
        out += ["", "## Entry points", "", ", ".join(f"{n}: {c}" for n, c in fw.most_common()), ""]
        out += ["| Framework | Method | Path | Where |", "|---|---|---|---|"]
        out += [f"| {a['framework']} | {a['method'] or ''} | {_route(a)} | {cite(a, base)} |" for a in api[:40]]
        if len(api) > 40:
            out.append(f"\n…and {len(api) - 40} more in `evidence/api.json`.")
    db = ev.get("database", {})
    if db.get("objects") or db.get("stores"):
        kinds = Counter(o["type"] for o in db.get("objects", []))
        out += ["", "## Database", "", f"- **Stores referenced:** {', '.join(s['name'] for s in db.get('stores', [])) or 'none detected'}",
                f"- **Objects in SQL files:** {', '.join(f'{k.lower()}: {v}' for k, v in kinds.most_common()) or 'none'}",
                f"- **ORM entities / mappers:** {len(db.get('entities', []))}"]
    t = ev.get("tests", {})
    d = ev.get("devops", {})
    out += ["", "## Tests and delivery", "",
            f"- **Tests:** {t.get('test_files', 0)} files, test/source ratio {t.get('ratio', 0):.2f}, frameworks: {', '.join(t.get('frameworks', [])) or 'none'}",
            f"- **CI:** {', '.join(sorted({c['system'] for c in d.get('ci', [])})) or 'none'} · **Containers:** {len(d.get('dockerfiles', []))} Dockerfile(s) · "
            f"**IaC:** {', '.join(d.get('iac', {}).keys()) or 'none'} · **Observability:** {', '.join(d.get('observability', [])) or 'none'}"]
    out += ["", "## Findings", ""]
    for area in AREA_TITLE:
        items = [f for f in findings if f["area"] == area]
        if not items:
            continue
        out += [f"### {AREA_TITLE[area]}", ""]
        for f in items:
            out += [f'<a id="{_anchor(f["id"])}"></a>', f"#### {f['id']} · {f['title']}", "",
                    f"**Severity:** {SEV_ICON[f['severity']]} · **Confidence:** {f['confidence']} · **Effort:** {f['effort']} · {KIND[f['kind']]}", "",
                    f"**What it means technically.** {f['technical_impact']}", "",
                    f"**What it means for the business.** {f['business_impact']}", "",
                    f"**Recommendation.** {f['recommendation']}", "", "**Evidence**", ""]
            for e in f["evidence"]:
                extra = f" — `{e['excerpt']}`" if e.get("excerpt") else (f" — {e['source']}" if e.get("source") else "")
                out.append(f"- {cite(e, base)}{extra}")
            if f.get("refs"):
                out += ["", "**References:** " + ", ".join(f"<{r}>" if r.startswith("http") else r for r in f["refs"])]
            out.append("")
    if ctx.get("not_found"):
        out += ["## Checked and not found", "", "What the specs asked about and the evidence did not show. Absence of evidence is reported, not guessed.", ""]
        for spec, items in ctx["not_found"].items():
            out += [f"- **{spec}:** " + "; ".join(items)]
        out.append("")
    if ctx.get("rejected"):
        out += ["## Rejected by the validator", "", f"{len(ctx['rejected'])} AI findings cited code that does not exist or does not say what was claimed. "
                "They are listed in `findings/rejected.json` and excluded from both reports.", ""]
    return "\n".join(out) + "\n"


def executive(ctx: dict) -> str:
    syn, findings = ctx["synthesis"], ctx["findings"]
    es = syn["executive_summary"]
    out = [f"# {ctx['name']}: modernization brief", "",
           f"Prepared on {ctx['date']} from the code itself. Every statement links to the technical evidence behind it.", "",
           f"## Status: {STATUS[es['status']]}", "", f"**{es['headline']}**", ""]
    out += [f"- {p['text']} {_refs(p['findings'])}" for p in es["points"]]
    out += ["", f"**Recommendation.** {es['recommendation']}", ""]
    if not syn["capabilities"]:
        out += ["## What the system does", "", "The entry points of this system do not name its business capabilities clearly enough "
                "to list them without guessing. Run the analysis with an AI provider (the capabilities spec reads the code) or "
                "list them with the people who use the system.", ""]
    if syn["capabilities"]:
        out += ["## What the system does", "", "Capabilities found in the code. The names come from the code: confirm them with the people who use the system.", "",
                "| Capability | Description | Where |", "|---|---|---|"]
        out += [f"| {c['name']} | {c['description']} {_refs(c['findings'])} | {', '.join(f'`{e}`' for e in c['evidence'][:2])} |" for c in syn["capabilities"]]
        out.append("")
    if syn["risks"]:
        out += ["## Risks", "", "Impact and probability from 1 (low) to 5 (high).", "",
                "| Risk | Impact | Probability | Evidence |", "|---|:---:|:---:|---|"]
        for r in sorted(syn["risks"], key=lambda r: -(r["impact"] * r["probability"])):
            out.append(f"| {r['statement']} | {r['impact']} | {r['probability']} | {_refs(r['findings'])} |")
        out += ["", _heatmap(syn["risks"]), ""]
    out += ["## Options", "", "The seven standard modernization strategies, sized for this system. Weeks are ranges for the stated team, not commitments.", "",
            "| Strategy | What it means | Cost | Risk | Weeks | |", "|---|---|:---:|:---:|:---:|---|"]
    for o in syn["options"]:
        out.append(f"| **{o['strategy']}** | {o['summary']} | {o['cost']} | {o['risk']} | {o['weeks'][0]}–{o['weeks'][1]} | {'⭐ recommended' if o['recommended'] else ''} |")
    rec = next((o for o in syn["options"] if o["recommended"]), None)
    if rec:
        out += ["", f"**Assumptions behind the recommended option ({rec['strategy']}):**", ""] + [f"- {a}" for a in rec["assumptions"]]
        if rec["findings"]:
            out += ["", f"Based on: {_refs(rec['findings'])}"]
    out += ["", "## Roadmap", ""]
    for p in syn["roadmap"]:
        out += [f"### {p['phase']} ({p['weeks'][0]}–{p['weeks'][1]} weeks)", "", p["goal"], ""]
        out += [f"- {m}" for m in p["milestones"]]
        if p["depends_on"]:
            out += ["", f"*Starts after:* {', '.join(p['depends_on'])}"]
        if p["findings"]:
            out += ["", f"*Addresses:* {_refs(p['findings'])}"]
        out.append("")
    verified = sum(1 for f in findings if f["kind"] == "verified")
    out += ["## How reliable is this?", "",
            f"- {len(findings)} findings: **{verified} verified by tools** (manifests, git, scanners) and **{len(findings) - verified} inferred by AI** "
            "and checked against the code they cite.",
            f"- {len(ctx.get('rejected', []))} AI statements were rejected because the code did not back them.",
            f"- Analysis: {ctx['provider_label']}. Full method and costs: `run.json`.", ""]
    if syn["faq"]:
        out += ["## Questions", ""]
        for q in syn["faq"]:
            out += [f"**{q['question']}**", "", q["answer"], ""]
    if syn["glossary"]:
        out += ["## Glossary", "", "| Term | Meaning |", "|---|---|"] + [f"| {g['term']} | {g['definition']} |" for g in syn["glossary"]] + [""]
    return "\n".join(out) + "\n"


def _heatmap(risks: list[dict]) -> str:
    grid = {(i, p): 0 for i in range(1, 6) for p in range(1, 6)}
    for r in risks:
        grid[(r["impact"], max(1, min(5, r["probability"])))] += 1
    rows = ["| Impact ↓ / Probability → | 1 | 2 | 3 | 4 | 5 |", "|---|:---:|:---:|:---:|:---:|:---:|"]
    for i in range(5, 0, -1):
        cells = []
        for p in range(1, 6):
            n = grid[(i, p)]
            color = "🟥" if i * p >= 15 else "🟧" if i * p >= 8 else "🟨" if i * p >= 4 else "🟩"
            cells.append(f"{color} {n}" if n else color)
        rows.append(f"| **{i}** | " + " | ".join(cells) + " |")
    return "\n".join(rows)
